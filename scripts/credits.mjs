import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { runnerImport } from 'vite';

const START = '<!-- credits:start -->';
const END = '<!-- credits:end -->';
const root = join(import.meta.dirname, '..');
const doc = join(root, 'docs', 'asset-credits.md');
const aboutModule = join(root, 'src', 'app', 'about-credits.ts');

const { module } = await runnerImport('/tools/assets/sources.ts', {
  root,
  configFile: false,
  logLevel: 'error',
});

const { module: about } = await runnerImport('/tools/about-credits.ts', {
  root,
  configFile: false,
  logLevel: 'error',
});

const text = readFileSync(doc, 'utf8');
const once = (marker) => {
  const at = text.indexOf(marker);
  if (at === -1 || text.indexOf(marker, at + 1) !== -1) {
    throw new Error(`docs/asset-credits.md must contain ${marker} exactly once`);
  }
  return at;
};
const start = once(START);
const end = once(END);
if (end < start)
  throw new Error('docs/asset-credits.md has its credits markers in the wrong order');
writeFileSync(
  doc,
  `${text.slice(0, start)}${START}${module.creditsSection(module.ASSET_SOURCES)}${text.slice(end)}`,
);

const source = `import type { AboutCredits } from './about-credits-types';

// Generated by \`pnpm credits\` from LICENSE, public/licenses and tools/assets/sources.ts; do not edit.
export const ABOUT_CREDITS: AboutCredits = ${JSON.stringify(about.aboutCredits(root))};
`;
writeFileSync(
  aboutModule,
  await format(source, { ...(await resolveConfig(aboutModule)), filepath: aboutModule }),
);
