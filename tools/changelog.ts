import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  CATEGORIES,
  inlineProblem,
  parseFragment,
  PR_URL,
  type Category,
  type ChangelogEntry,
  type Release,
} from '../src/app/changelog-entries';

const HEADINGS: Record<Category, string> = {
  added: 'Added',
  changed: 'Changed',
  deprecated: 'Deprecated',
  removed: 'Removed',
  fixed: 'Fixed',
  security: 'Security',
};
export const VERSION_RE = /^\d+\.\d+\.\d+$/;
export const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

export const fragmentFiles = (dir: string): string[] =>
  readdirSync(dir)
    .filter((file) => file !== 'README.md' && file !== 'released.json')
    .sort((a, b) => Number.parseInt(a, 10) - Number.parseInt(b, 10) || a.localeCompare(b));

export const loadFragments = (dir: string): ChangelogEntry[] =>
  fragmentFiles(dir).map((file) => parseFragment(file, readFileSync(join(dir, file), 'utf8')));

export const loadReleases = (dir: string): unknown =>
  JSON.parse(readFileSync(join(dir, 'released.json'), 'utf8')) as unknown;

const entryProblems = (entry: unknown, where: string, seen: Set<string>): string[] => {
  if (!isRecord(entry)) return [`${where}: not an object`];
  const out: string[] = [];
  const { id, category, prs, en } = entry;
  if (typeof id !== 'string' || id === '') out.push(`${where}: id must be a non-empty string`);
  else if (seen.has(id)) out.push(`${where}: duplicate id ${id}`);
  else seen.add(id);
  if (!CATEGORIES.includes(category as Category)) out.push(`${where}: unknown category`);
  if (
    !Array.isArray(prs) ||
    prs.length === 0 ||
    !prs.every((pr) => Number.isInteger(pr) && (pr as number) > 0) ||
    new Set(prs).size !== prs.length
  )
    out.push(`${where}: prs must be a non-empty list of distinct PR numbers`);
  if (typeof en !== 'string') out.push(`${where}: en must be a string`);
  else {
    const problem = inlineProblem(en);
    if (problem !== null) out.push(`${where}: en ${problem}`);
  }
  const extra = Object.keys(entry).filter((key) => !['id', 'category', 'prs', 'en'].includes(key));
  if (extra.length > 0) out.push(`${where}: unknown keys ${extra.join(', ')}`);
  return out;
};

/** Schema problems of released.json; `fragmentIds` take part in the id uniqueness check. */
export const releaseProblems = (data: unknown, fragmentIds: readonly string[] = []): string[] => {
  if (!Array.isArray(data)) return ['released.json must be an array of releases'];
  const out: string[] = [];
  const seen = new Set<string>(fragmentIds);
  data.forEach((release: unknown, index) => {
    const where = `release ${String(index)}`;
    if (!isRecord(release)) {
      out.push(`${where}: not an object`);
      return;
    }
    const { version, date, entries } = release;
    if (version === null) {
      if (index !== 0) out.push(`${where}: the unreleased group (version null) must come first`);
      if (date !== undefined) out.push(`${where}: an unreleased group has no date`);
    } else if (typeof version !== 'string' || !VERSION_RE.test(version))
      out.push(`${where}: version must be null or x.y.z`);
    else if (typeof date !== 'string' || !DATE_RE.test(date))
      out.push(`${where}: a released version needs a YYYY-MM-DD date`);
    if (!Array.isArray(entries)) out.push(`${where}: entries must be an array`);
    else
      entries.forEach((entry: unknown, i) =>
        out.push(...entryProblems(entry, `${where} entry ${String(i)}`, seen)),
      );
  });
  return out;
};

const line = (entry: ChangelogEntry): string => {
  const links = entry.prs.map((pr) => `[#${String(pr)}](${PR_URL}${String(pr)})`).join(', ');
  return `- ${entry.en.slice(0, -1)} (${links}).`;
};

export const section = (title: string, entries: readonly ChangelogEntry[]): string => {
  const blocks = [`## ${title}`];
  for (const category of CATEGORIES) {
    const items = entries.filter((entry) => entry.category === category);
    if (items.length > 0) blocks.push(`### ${HEADINGS[category]}`, items.map(line).join('\n'));
  }
  return blocks.join('\n\n');
};

export const renderChangelog = (releases: readonly Release[]): string => {
  const pending = releases.find((release) => release.version === null);
  const unreleased = pending?.entries ?? [];
  const tagged = releases.filter((release) => release.version !== null);
  const intro = [
    '# Changelog',
    'All notable changes to this project are documented in this file.',
    `The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.1.0/).${
      tagged.length === 0
        ? ' The project has no tagged release yet, so everything is listed under Unreleased.'
        : ''
    }`,
    'This file is generated by `pnpm changelog` from `changelog.d/released.json`; pending fragments are not listed until a release folds them in. Do not edit it by hand. See `changelog.d/README.md`.',
  ];
  const sections = [
    section('[Unreleased]', unreleased),
    ...tagged.map((release) =>
      section(`[${release.version ?? ''}] - ${release.date ?? ''}`, release.entries),
    ),
  ];
  return `${[...intro, ...sections].join('\n\n')}\n`;
};

/** The full CHANGELOG.md for the repository at `root`. Throws when released.json is malformed. */
export const generateChangelog = (root: string): string => {
  const dir = join(root, 'changelog.d');
  const fragments = loadFragments(dir);
  const data = loadReleases(dir);
  const problems = releaseProblems(
    data,
    fragments.map((fragment) => fragment.id),
  );
  if (problems.length > 0) throw new Error(`changelog.d/released.json:\n${problems.join('\n')}`);
  return renderChangelog(data as Release[]);
};

export interface ReleaseState {
  /** `version` of package.json. */
  version: string;
  /** True when `version` is the head released group of released.json and no fragment is pending. */
  release: boolean;
}

/** Whether the tree at `root` is a release build; only then is `version` shown as the app's. */
export const releaseState = (root: string): ReleaseState => {
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
    version?: unknown;
  };
  if (typeof version !== 'string' || !VERSION_RE.test(version))
    throw new Error('package.json: version must be x.y.z');
  const dir = join(root, 'changelog.d');
  const releases = loadReleases(dir);
  const head: unknown = Array.isArray(releases) ? releases[0] : undefined;
  const headVersion = isRecord(head) ? head['version'] : undefined;
  return { version, release: headVersion === version && fragmentFiles(dir).length === 0 };
};
