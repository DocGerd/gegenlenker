import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { sha256 } from '../assets/provenance';
import {
  bakeHdriLight,
  parseRadianceHdr,
  sunClamp,
  upperLuminance,
  type RadianceImage,
} from './hdri-light';
import { inputsSha256, SKY_HDR } from './sky-build';

const srgb = (v: number): number => (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);

/** The upper hemisphere with the sun scaled down to the clamp, each channel as x / (1 + x) in sRGB. */
export function skyPixels(image: RadianceImage): {
  width: number;
  height: number;
  rgba: Uint8Array;
} {
  const { width, rgb } = image;
  const lum = upperLuminance(image);
  const clamp = sunClamp(lum);
  const rgba = new Uint8Array(lum.length * 4);
  lum.forEach((l, i) => {
    const scale = l > clamp ? clamp / l : 1;
    for (let c = 0; c < 3; c++) {
      const x = (rgb[i * 3 + c] ?? 0) * scale;
      rgba[i * 4 + c] = Math.round(255 * Math.min(1, Math.max(0, srgb(x / (1 + x)))));
    }
    rgba[i * 4 + 3] = 255;
  });
  return { width, height: image.height / 2, rgba };
}

/** Reads the downloaded .hdr under `root`, checked against its registered hash. */
export function readSkyImage(root: string): RadianceImage {
  const path = join(root, SKY_HDR.path);
  if (!existsSync(path)) throw new Error(`${SKY_HDR.path} is missing: download ${SKY_HDR.url}`);
  const hdr = new Uint8Array(readFileSync(path));
  if (sha256(hdr) !== SKY_HDR.sha256) {
    throw new Error(`${SKY_HDR.path} is not the sky HDRI (${SKY_HDR.url})`);
  }
  return parseRadianceHdr(hdr);
}

/** The text of `src/render/hdri-light.ts`, baked from the same .hdr as the ktx2 it names. */
export function hdriLightModule(root: string, ktx2: Uint8Array): string {
  const light = {
    inputsSha256: inputsSha256(root),
    hdrSha256: SKY_HDR.sha256,
    skyKtx2Sha256: sha256(ktx2),
    ...bakeHdriLight(readSkyImage(root)),
  };
  return [
    '// Generated by tools/textures/sky-pixels.ts (pnpm texture sky); do not edit.',
    `export const HDRI_LIGHT = ${JSON.stringify(light)} as const;`,
    '',
  ].join('\n');
}
