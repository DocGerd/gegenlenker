// Usage: node tools/textures/sky-build.ts [<4k.hdr>]   (pnpm sky:texture)
// Encodes src/render/assets/sky.ktx2 from the sky HDRI and bakes src/render/hdri-light.ts from the
// same file. The .hdr is not committed; it is read from SKY_HDR.path unless a path is given.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  bakeHdriLight,
  parseRadianceHdr,
  sunClamp,
  upperLuminance,
  type RadianceImage,
} from './hdri-light.ts';

export const ROOT = join(import.meta.dirname, '../..');

export const SKY_HDR = {
  page: 'https://polyhaven.com/a/kloofendal_48d_partly_cloudy_puresky',
  url: 'https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/4k/kloofendal_48d_partly_cloudy_puresky_4k.hdr',
  sha256: '3061c00a16ecae748e84fd6c44c04804f539c118bb66325db858bad87b11bf88',
  path: 'tools/textures/input/kloofendal_48d_partly_cloudy_puresky_4k.hdr',
} as const;

export const SKY_FILES = {
  /** Everything the texture and the bake depend on besides the .hdr. */
  sources: ['tools/textures/sky-build.ts', 'tools/textures/hdri-light.ts'],
  ktx2: 'src/render/assets/sky.ktx2',
  bake: 'src/render/hdri-light.ts',
} as const;

/** sRGB colour, no mips: the dome's u wraps at one azimuth, where a mip chain would draw a seam. */
export const ENCODER_OPTIONS = {
  isUASTC: true,
  uastcLDRQualityLevel: 3,
  needSupercompression: true,
  enableRDO: true,
  rdoQualityLevel: 3,
  generateMipmap: false,
  isPerceptual: true,
  isSetKTX2SRGBTransferFunc: true,
  isKTX2File: true,
} as const;

export const KV_INPUTS = 'gegenlenker.inputsSha256';

export const sha256 = (data: string | Uint8Array): string =>
  createHash('sha256').update(data).digest('hex');

const lf = (file: string, root: string): string =>
  readFileSync(join(root, file), 'utf8').replaceAll('\r\n', '\n');

/** Source files (LF-normalised), the encoder settings and the .hdr's hash. */
export const inputsSha256 = (root = ROOT): string =>
  sha256(
    JSON.stringify([
      ...SKY_FILES.sources.map((file) => [file, lf(file, root)]),
      ENCODER_OPTIONS,
      SKY_HDR.sha256,
    ]),
  );

const srgb = (v: number): number => (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);

/** The upper hemisphere with the sun scaled down to the clamp, each channel as x / (1 + x) in sRGB. */
export function skyPixels(image: RadianceImage): {
  width: number;
  height: number;
  rgba: Uint8Array;
} {
  const { width, rgb } = image;
  const lum = upperLuminance(image);
  const clamp = sunClamp(lum);
  const rgba = new Uint8Array(lum.length * 4);
  lum.forEach((l, i) => {
    const scale = l > clamp ? clamp / l : 1;
    for (let c = 0; c < 3; c++) {
      const x = (rgb[i * 3 + c] ?? 0) * scale;
      rgba[i * 4 + c] = Math.round(255 * Math.min(1, Math.max(0, srgb(x / (1 + x)))));
    }
    rgba[i * 4 + 3] = 255;
  });
  return { width, height: image.height / 2, rgba };
}

if (import.meta.main) {
  const { encodeToKTX2 } = await import('ktx2-encoder');
  const { format, resolveConfig } = await import('prettier');
  const hdrPath = process.argv[2] ?? join(ROOT, SKY_HDR.path);
  const hdr = new Uint8Array(readFileSync(hdrPath));
  if (sha256(hdr) !== SKY_HDR.sha256) {
    throw new Error(`${hdrPath} is not the sky HDRI (${SKY_HDR.url})`);
  }
  const image = parseRadianceHdr(hdr);
  const baked = bakeHdriLight(image);
  const pixels = skyPixels(image);
  const inputs = inputsSha256();

  // The encoder logs every slice to stdout.
  const log = console.log;
  console.log = () => undefined;
  const ktx2 = await encodeToKTX2(pixels.rgba, {
    ...ENCODER_OPTIONS,
    imageDecoder: () =>
      Promise.resolve({ width: pixels.width, height: pixels.height, data: pixels.rgba }),
    kvData: { [KV_INPUTS]: inputs },
  });
  console.log = log;
  writeFileSync(join(ROOT, SKY_FILES.ktx2), ktx2);

  const light = {
    inputsSha256: inputs,
    hdrSha256: SKY_HDR.sha256,
    skyKtx2Sha256: sha256(ktx2),
    ...baked,
  };
  const out = join(ROOT, SKY_FILES.bake);
  const source = [
    '// Generated by tools/textures/sky-build.ts (pnpm sky:texture); do not edit.',
    `export const HDRI_LIGHT = ${JSON.stringify(light)} as const;`,
    '',
  ].join('\n');
  writeFileSync(out, await format(source, { ...(await resolveConfig(out)), filepath: out }));
  console.log(`${SKY_FILES.ktx2}: ${ktx2.length} bytes`);
}
